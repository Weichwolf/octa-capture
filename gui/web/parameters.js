export function reverbTimeText(index) {
  return Number.isInteger(index) && index >= 0 && index < 50 ? ((index + 1) / 10).toFixed(1) : '--';
}
export const GRAPH_MIN_DB = -60;
export const PREAMP_MAX = Object.freeze({sensitivity: 100, gate: 50, threshold: 50,
  gain: 74, attack: 25, release: 45, ratio: 8});

export function volumeIndex(value) {
  if (!Number.isInteger(value) || value < 0 || value > VOLUME.at(-1)) return null;
  let low = 0, high = VOLUME.length - 1;
  while (low < high) {
    const middle = Math.floor((low + high) / 2);
    if (VOLUME[middle] < value) low = middle + 1;
    else high = middle;
  }
  if (low === 0) return 0;
  return value - VOLUME[low - 1] < VOLUME[low] - value ? low - 1 : low;
}

export function volumeText(value) {
  if (value === 0) return '-INF dB';
  return `${(20 * Math.log10(value / 0x200000)).toFixed(1)} dB`;
}

export function parameterText(parameter, index) {
  if (!Number.isInteger(index) || index < 0 || index > PREAMP_MAX[parameter]) return '--';
  switch (parameter) {
    case 'sensitivity': return `${(index / 2).toFixed(1)} dB`;
    case 'gate': return index === 0 ? '-INF dB' : `${(index - 70).toFixed(1)} dB`;
    case 'threshold': case 'gain':
      return `${index > 40 && index < 50 ? '- ' + (50 - index).toFixed(1) : (index - 50).toFixed(1)} dB`;
    case 'attack': return `${ATTACK[index]} ms`;
    case 'release': return `${RELEASE[index]} ms`;
    case 'ratio': return RATIO_TEXT[index];
    default: return '--';
  }
}

export function panToWire(position) {
  return Math.floor((position * 16384 + 50) / 100);
}

export function wireToPan(value) {
  return Math.floor((value * 100 + 8192) / 16384);
}

export function panText(position) {
  return position === 100 ? '0%' : `${Math.abs(position - 100)}%${position < 100 ? 'L' : 'R'}`;
}

export function outputJackStates(rateIndex, bus, routes) {
  const selected = rateIndex === 3 ? 0 : bus;
  return routes.map((route, pair) => rateIndex === 3 && pair >= 2 ? 'unavailable' :
    route === selected ? 'assigned' : 'other');
}

// Both reference panels truncate twice the entered dB value to the wire index.
// The Windows edit is four characters wide and commits on Enter/focus loss.
export function sensitivityIndex(text) {
  if (typeof text !== 'string' || text.length > 4 ||
      !/^(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)$/.test(text)) return null;
  const value = Number(text);
  return Number.isFinite(value) && value >= 0 && value <= 50 ? Math.trunc(value * 2) : null;
}

// The reference keeps the configured curve visible (dimmed) while bypassed.
export function compressorOutput(input, compressor) {
  const threshold = compressor.threshold_index - 50;
  const gain = compressor.gain_index - 50;
  const ratio = RATIO[compressor.ratio_index];
  if (input <= threshold) return input + gain;
  return (ratio === 0 ? threshold : threshold + (input - threshold) / ratio) + gain;
}
